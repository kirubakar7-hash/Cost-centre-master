/**
 * Excel output for the Finance reports. Every sheet starts with the same
 * header block (report, filters, generated at / by, classification), then one
 * table with a styled header row (bold white on SolidPro blue), an autofilter
 * and frozen panes. Exception cells are red, exception rows lightly tinted.
 */
import type { FilterLines } from '@/lib/reports';

const BLUE = 'FF16469D';
const RED = 'FFE01A22';
const GREY = 'FF939597';
const FLAG_FILL = 'FFFDE3E4';
const MAX_CELL = 32_000; // Excel's hard limit is 32,767 characters
export const CLASSIFICATION = 'Internal use only — Solidpro Engineering Support Private Limited';

export const AMT = '#,##0';
export const AMT2 = '#,##0.00';
export const PCT = '0.0%';

export interface Column {
  header: string;
  key: string;
  width?: number;
  numFmt?: string;
  wrap?: boolean;
}

export type Cell = string | number | boolean | null | undefined;

export interface SheetSpec {
  name: string;
  columns: Column[];
  rows: Record<string, Cell>[];
  /** Tint the whole row (an exception). */
  flagRow?: (row: Record<string, Cell>) => boolean;
  /** Keys of cells to show in bold red. */
  redCells?: (row: Record<string, Cell>) => string[];
  /** Extra lines under the header block (italic grey). */
  notes?: string[];
  /** Total matching rows when the sheet was cut off at the export cap. */
  totalRows?: number;
}

export interface ReportMeta {
  title: string;
  filters: FilterLines;
  generatedBy: string;
  generatedAt: Date;
}

const utcStamp = (d: Date) => `${d.toISOString().slice(0, 19).replace('T', ' ')} UTC`;
const sheetName = (s: string) => s.replace(/[[\]:*?/\\]/g, ' ').slice(0, 31);

function cellValue(v: Cell): string | number | boolean | null {
  if (v === undefined || v === null) return null;
  if (typeof v === 'string') return v.length > MAX_CELL ? `${v.slice(0, MAX_CELL)}… [truncated]` : v;
  return v;
}

export async function buildWorkbook(meta: ReportMeta, sheets: SheetSpec[]): Promise<Buffer> {
  const ExcelJS = (await import('exceljs')).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = 'SolidPro Cost Centre Portal';
  wb.created = meta.generatedAt;
  wb.title = meta.title;
  wb.subject = CLASSIFICATION;

  for (const spec of sheets) {
    const ws = wb.addWorksheet(sheetName(spec.name));
    ws.columns = spec.columns.map((c) => ({ key: c.key, width: c.width ?? 16 }));

    // ---- header block ---------------------------------------------------
    const title = sheets.length > 1 ? `${meta.title} — ${spec.name}` : meta.title;
    ws.addRow([`SolidPro Cost Centre Portal — ${title}`]).font = { bold: true, size: 14, color: { argb: BLUE }, name: 'Maven Pro' };
    ws.addRow([CLASSIFICATION]).font = { bold: true };
    const label = (k: string, v: string, bold = false) => {
      const row = ws.addRow([k, v]);
      row.getCell(1).font = { bold: true };
      if (bold) row.getCell(2).font = { bold: true, color: { argb: RED } };
    };
    // One line for every filter keeps the block short (it stays frozen above the table)
    label('Filters', meta.filters.map(([k, v]) => `${k}: ${v}`).join(' · '));
    label('Generated at', utcStamp(meta.generatedAt));
    label('Generated by', meta.generatedBy);
    const cut = spec.totalRows !== undefined && spec.totalRows > spec.rows.length;
    label(
      'Rows',
      cut
        ? `${spec.rows.length.toLocaleString('en-US')} of ${spec.totalRows!.toLocaleString('en-US')} — cut off at the export limit; narrow the filters`
        : spec.rows.length.toLocaleString('en-US'),
      cut,
    );
    for (const n of spec.notes ?? []) ws.addRow([n]).font = { italic: true, color: { argb: GREY } };
    ws.addRow([]);

    // ---- table ------------------------------------------------------------
    const header = ws.addRow(spec.columns.map((c) => c.header));
    header.font = { bold: true, color: { argb: 'FFFFFFFF' }, name: 'Maven Pro' };
    header.alignment = { vertical: 'middle', wrapText: true };
    header.eachCell((c) => {
      c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BLUE } };
    });
    const headerRow = header.number;

    for (const r of spec.rows) {
      const row = ws.addRow(spec.columns.map((c) => cellValue(r[c.key])));
      spec.columns.forEach((c, i) => {
        const cell = row.getCell(i + 1);
        if (c.numFmt) cell.numFmt = c.numFmt;
        if (c.wrap) cell.alignment = { wrapText: true, vertical: 'top' };
        else cell.alignment = { vertical: 'top' };
      });
      if (spec.flagRow?.(r)) {
        for (let i = 1; i <= spec.columns.length; i++) row.getCell(i).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: FLAG_FILL } };
      }
      for (const key of spec.redCells?.(r) ?? []) {
        const idx = spec.columns.findIndex((c) => c.key === key);
        if (idx >= 0) row.getCell(idx + 1).font = { bold: true, color: { argb: RED } };
      }
    }
    if (spec.rows.length === 0) ws.addRow(['No rows.']).font = { italic: true, color: { argb: GREY } };

    ws.views = [{ state: 'frozen', ySplit: headerRow }];
    if (spec.rows.length > 0) {
      ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow + spec.rows.length, column: spec.columns.length } };
    }
    ws.addRow([]);
    ws.addRow([CLASSIFICATION]).font = { italic: true, color: { argb: GREY } };
  }

  return Buffer.from(await wb.xlsx.writeBuffer());
}
